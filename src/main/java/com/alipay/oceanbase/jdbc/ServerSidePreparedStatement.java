package com.alipay.oceanbase.jdbc;

import com.alipay.oceanbase.jdbc.internal.util.exceptions.ExceptionFactory;

import java.sql.SQLException;

public class ServerSidePreparedStatement extends JDBC4ServerPreparedStatement {
    /**
     * Constructor for creating Server prepared statement.
     *
     * @param isObFunction
     * @param connection           current connection
     * @param sql                  Sql String to prepare
     * @param resultSetScrollType  one of the following <code>ResultSet</code> constants: <code>
     *                             ResultSet.TYPE_FORWARD_ONLY</code>, <code>ResultSet.TYPE_SCROLL_INSENSITIVE</code>, or
     *                             <code>ResultSet.TYPE_SCROLL_SENSITIVE</code>
     * @param resultSetConcurrency a concurrency type; one of <code>ResultSet.CONCUR_READ_ONLY</code>
     *                             or <code>ResultSet.CONCUR_UPDATABLE</code>
     * @param autoGeneratedKeys    a flag indicating whether auto-generated keys should be returned; one
     *                             of <code>Statement.RETURN_GENERATED_KEYS</code> or <code>Statement.NO_GENERATED_KEYS</code>
     * @param exceptionFactory     Exception factory
     * @throws SQLException exception
     */
    public ServerSidePreparedStatement(boolean isObFunction, OceanBaseConnection connection,
                                       String sql, int resultSetScrollType,
                                       int resultSetConcurrency, int autoGeneratedKeys,
                                       ExceptionFactory exceptionFactory) throws SQLException {
        super(isObFunction, connection, sql, resultSetScrollType, resultSetConcurrency,
            autoGeneratedKeys, exceptionFactory);
    }
}
